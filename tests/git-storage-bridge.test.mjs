function receipt(id,userId,previous=null) {
  const r={id,userId,fileName:'synthetic',filePath:'synthetic',fileHash:'sha256:'+'a'.repeat(64),modelName:'synthetic-claim',modelProvider:'synthetic',countryOfOrigin:'US',prevEntryHash:previous,signedAt:'2026-11-07T00:00:00.000Z',receiptVersion:'v1',publicKey};
  r.entryHash=hash([r.fileHash,r.modelName,r.modelProvider,r.countryOfOrigin,previous||'genesis',r.signedAt].join('|'));
  r.signature=sign(null,Buffer.from(`${r.entryHash}|${r.fileHash}|${r.signedAt}`),keys.privateKey).toString('base64');
  return r;
}
